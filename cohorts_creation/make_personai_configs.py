"""Write one complete config file per PersonAI run into cohorts_creation/personai_configs/.

Every file is the template cohorts_creation/final_config.yaml with the settings of one row of the setup table filled in
(name, cluster_forced, cluster_algo, cluster_assign, coefficients, qns_features, worst_cluster, plus extremes_filter and iterations,
which only the optional extremes variant changes). To run an experiment, pass its file to cohort_modeling.py. Nothing has to be edited between runs.

Usage, from the project folder:
    person_ai_venv\\Scripts\\python.exe cohorts_creation\\make_personai_configs.py
Change a shared setting in final_config.yaml (or a setup below) and run the script again to regenerate all files.
"""
import argparse
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--template", default=os.path.join(HERE, "final_config.yaml"))
ap.add_argument("--out", default=os.path.join(HERE, "personai_configs"))
args = ap.parse_args()

LIST_A = ["swls_score", "bfi2s_extraversion", "bfi2s_agreeableness", "bfi2s_conscientiousness", "bfi2s_emotionality", "bfi2s_openness"]
LIST_B = LIST_A[1:]
SWLS_EXT = {"column": "swls_score", "lower_q": 0.25, "upper_q": 0.75}
COLD = dict(cluster_algo="kmeans", cluster_assign="questions", coefficients=[0.5, 0, 0.5])
WARM = dict(cluster_forced="-1", cluster_algo="spectral", cluster_assign="performance")

# (setup, description, settings that differ from the defaults: qns_features [], extremes_filter None, iterations 72)
SETUPS = [
    ("1", "cold start, sex", dict(name="PersonAI_cold_sex", cluster_forced="sex", **COLD)),
    ("2", "cold start, agreeableness", dict(name="PersonAI_cold_bfi2s_agreeableness", cluster_forced="bfi2s_agreeableness", **COLD)),
    ("3", "cold start, life satisfaction (SWLS)", dict(name="PersonAI_cold_swls_score", cluster_forced="swls_score", **COLD)),
    ("4", "cold start, all surveys (list A)", dict(name="PersonAI_cold_survey", cluster_forced="-1", **COLD, qns_features=LIST_A)),
    ("5", "cold start, Big Five (list B)", dict(name="PersonAI_cold_big5", cluster_forced="-1", **COLD, qns_features=LIST_B)),
    ("6", "warm start, vote distribution + cross-model performance", dict(name="PersonAI_warm_Cross_Dist_survey", **WARM, coefficients=[0.5, 0, 0.5], qns_features=LIST_A)),
    ("7", "warm start, cross-model performance only (named Dist for historical reasons)", dict(name="PersonAI_warm_Dist_survey", **WARM, coefficients=[0, 0, 1], qns_features=LIST_A)),
    ("optional", "cold start, life satisfaction (SWLS), extremes only", dict(name="PersonAI_cold_swls_score_ext", cluster_forced="swls_score", **COLD, extremes_filter=SWLS_EXT, iterations=44)),
]
DEFAULTS = dict(qns_features=[], extremes_filter=None, iterations=72)
# the settings that differ between runs, in the order of the setup table on the run-config page
RUN_KEYS = ["name", "cluster_forced", "cluster_algo", "cluster_assign", "coefficients", "qns_features", "extremes_filter", "iterations", "worst_cluster"]

# the shared settings as documented on the run-config page; a template that deviates is reported, not silently copied
DOCUMENTED = dict(seed=42, leave_1_out=True, dataset="personai/final_main_dataset_no_missing_ALLENC_new_bpm.csv",
                  dataset_with_time="personai/final_main_dataset_no_missing_ALLENC_with_time_and_hr_age.csv", data_set_with_time_bool=True,
                  dataset_survey="personai/cold_start_data_full.csv", variable_features=["t_ubi", "rh_ubi", "hr_ubi", "bpm_time_diff_log", "CO2", "activity"],
                  fixed_features=["sex", "fitness_level", "height_cm", "weight_kg"], precomputed_pcm=True, pcm_file="PersonAi/dict_pcm_rdf_sensor_at_f1_micro_personai",
                  excluded_users=["id016"], parameter_finetuning=False, cluster_num=2, cluster_predict_criteria="cold")

with open(args.template, encoding="utf-8") as f:
    template = yaml.safe_load(f)
deviations = {k: (template.get(k), v) for k, v in DOCUMENTED.items() if template.get(k) != v}
if deviations:
    print("WARNING: the template differs from the shared settings documented on the page:")
    for k, (have, want) in deviations.items():
        print(f"   {k}: template has {have!r}, page says {want!r}")

os.makedirs(args.out, exist_ok=True)
written = []
for num, desc, over in SETUPS:
    for wrong in (False, True):
        cfg = dict(template)
        cfg.update(DEFAULTS)
        cfg.update(over)
        if wrong:
            cfg["name"] += "_wrong"
        cfg["worst_cluster"] = wrong
        header = (f"# PersonAI run {cfg['name']}: setup {num}, {desc}{' (wrong twin: every new person goes to the wrong cohort)' if wrong else ''}\n"
                  f"# Generated by cohorts_creation/make_personai_configs.py from cohorts_creation/final_config.yaml. Do not edit by hand:\n"
                  f"# change the template or the script and run the script again.\n"
                  f"# Start with: person_ai_venv\\Scripts\\python.exe cohorts_creation\\cohort_modeling.py cohorts_creation\\personai_configs\\{cfg['name']}.yaml\n\n")
        run_part = {k: cfg[k] for k in RUN_KEYS}
        shared_part = {k: v for k, v in cfg.items() if k not in RUN_KEYS}
        dump = lambda d: yaml.dump(d, sort_keys=False, default_flow_style=None, allow_unicode=True, width=200)
        text = ("# ---- settings of this run (the columns of the setup table; extremes_filter and iterations only change in the optional variant) ----\n" + dump(run_part)
                + "\n# ---- settings shared by all PersonAI runs ----\n" + dump(shared_part))
        path = os.path.join(args.out, cfg["name"] + ".yaml")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(header + text)
        written.append(cfg["name"])
print(f"wrote {len(written)} config files to {args.out}")
for n in written:
    print("  ", n + ".yaml")
